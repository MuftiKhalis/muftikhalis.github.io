def svg(slug):
    rows = G.get(slug) or G["map"]
    off = (7 - len(rows)) // 2
    rects = "".join(f'<rect x="{x}" y="{y + off}" width="1" height="1"/>'
                    for y, row in enumerate(rows) for x, c in enumerate(row) if c == "#")
    return f'<svg viewBox="0 0 7 7" fill="currentColor" aria-hidden="true">{rects}</svg>'


def gl(slug, group, size=""):
    """A coloured square with the pixel glyph. group: maps, everyday, files, learn, games or pages."""
    cls = f"gl grp-{group}" + (f" {size}" if size else "")
    return f'<span class="{cls}" aria-hidden="true">{svg(slug)}</span>'
